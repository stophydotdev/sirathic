import { z } from "zod";
import { cacheFor } from "../cache";
import { stophy } from "../stophy";

const TRANSCRIPT_CHARS = 20_000;
const DAY_MS = 24 * 60 * 60_000;

export const youtubeTranscriptInput = z.object({
  videoUrl: z
    .url()
    .describe("A YouTube video link, from youtubeSearch or the user"),
  language: z
    .string()
    .regex(/^[A-Za-z]{2,3}(?:[-_][A-Za-z0-9]{2,4})?$/u)
    .optional()
    .describe(
      "Transcript language, like en or ar. Leave out for the video's own",
    ),
});

const transcript = z.object({
  url: z.string(),
  language: z.string().nullable(),
  autoGenerated: z.boolean(),
  durationSeconds: z.number().nullable(),
  text: z.string(),
  truncated: z.boolean(),
});

const transcriptCache = cacheFor({
  namespace: "youtube-transcript:v1",
  schema: transcript,
  freshMs: 30 * DAY_MS,
  keepMs: 90 * DAY_MS,
});

export const youtubeTranscript = (
  input: z.input<typeof youtubeTranscriptInput>,
) => {
  const { videoUrl, language } = youtubeTranscriptInput.parse(input);
  return transcriptCache(`${videoUrl}|${language ?? ""}`, async () => {
    const { data } = await stophy.youtube.transcript({ videoUrl, language });
    const text = data.text ?? "";
    return {
      url: data.videoUrl ?? videoUrl,
      language: data.language ?? null,
      autoGenerated: data.isAutoGenerated ?? false,
      durationSeconds: data.durationSeconds ?? null,
      text: text.slice(0, TRANSCRIPT_CHARS),
      truncated: text.length > TRANSCRIPT_CHARS,
    };
  });
};
